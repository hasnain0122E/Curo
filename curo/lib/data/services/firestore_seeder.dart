import 'package:cloud_firestore/cloud_firestore.dart';

/// Seeds `labs` and `pharmacies` collections on first launch.
/// Each collection is seeded independently — safe to call every launch.
class FirestoreSeeder {
  FirestoreSeeder._();

  static Future<void> seedIfEmpty(FirebaseFirestore db) async {
    await Future.wait([
      _seedCollection(db, 'labs', _labData),
      _seedCollection(db, 'pharmacies', _pharmacyData),
    ]);
  }

  static Future<void> _seedCollection(
    FirebaseFirestore db,
    String collection,
    List<Map<String, dynamic>> Function() dataFn,
  ) async {
    final existing = await db.collection(collection).limit(1).get();
    if (existing.docs.isNotEmpty) return;
    final data = dataFn();
    final batch = db.batch();
    for (final item in data) {
      batch.set(db.collection(collection).doc(item['id'] as String), item);
    }
    await batch.commit();
  }

